#!/usr/bin/env python3
"""Keep dark overrides complete as the existing monochrome stylesheet grows.

Only colour declarations change; responsive layout and chessboard/piece colours
stay in the main stylesheet. Semantic status/medal colours have explicit styling
in theme.css. No browser image inversion is used.
"""
import argparse
import re
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
HEX=re.compile(r'#[0-9a-fA-F]{8}\b|#[0-9a-fA-F]{6}\b|#[0-9a-fA-F]{3}\b|\bwhite\b|\bblack\b')


def neutral(token):
    token={'white':'#ffffff','black':'#000000'}.get(token,token)
    if len(token)==9:return None  # Preserve translucent decorations/shadows.
    digits=token[1:]
    if len(digits)==3:digits=''.join(c*2 for c in digits)
    rgb=[int(digits[i:i+2],16) for i in (0,2,4)]
    if max(rgb)-min(rgb)>25:return None
    return sum(rgb)/3


def convert(prop,value):
    def replace(match):
        token=match.group(0);level=neutral(token)
        if level is None:return token
        if prop=='color':
            if level>=190:return token
            return 'var(--theme-text)' if level<75 else 'var(--theme-muted)'
        if prop.startswith('background'):
            if level<160:return token
            return 'var(--theme-surface)' if level>=245 else 'var(--theme-soft)'
        return 'var(--theme-border)'
    result=HEX.sub(replace,value)
    if prop=='color':
        result=re.sub(r'var\(--(?:pine|pine-dark|forest|lime|ink|danger)\)','var(--theme-text)',result)
    if prop.startswith('background'):
        result=result.replace('var(--white)','var(--theme-surface)')
    return result


def build():
    css=re.sub(r'/\*.*?\*/','',(ROOT/'static/style.css').read_text(),flags=re.S)
    blocks=[]
    for match in re.finditer(r'([^{}]+)\{([^{}]*)\}',css):
        selector,body=match.groups();selector=selector.strip()
        if selector.startswith('@') or ':root' in selector or 'replay-square' in selector or 'replay-piece' in selector:
            continue
        declarations=[]
        for declaration in body.split(';'):
            if ':' not in declaration:continue
            prop,value=map(str.strip,declaration.split(':',1))
            if prop not in ('color','background','background-color','border','border-color','border-top','border-bottom','border-left','border-right','border-top-color','border-bottom-color','border-left-color','border-right-color','outline','outline-color'):
                continue
            changed=convert(prop,value)
            if changed!=value:declarations.append(prop+':'+changed)
        if declarations:
            scoped=','.join(':root[data-theme="dark"] '+part.strip() for part in selector.split(','))
            blocks.append(scoped+'{'+ ';'.join(declarations)+'}')
    return '/* Generated by tools/build_dark_theme.py; edit style.css or theme.css. */\n'+'\n'.join(blocks)+'\n'


if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
    path=ROOT/'static/dark.css';result=build()
    if args.check:
        if not path.exists() or path.read_text()!=result:raise SystemExit('Dark stylesheet is out of date. Run tools/build_dark_theme.py.')
        print('Dark stylesheet is current')
    else:
        path.write_text(result);print('Built static/dark.css')
